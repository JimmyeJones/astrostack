"""🔒 The incoming folder is strictly read-only — enforced here, not just documented.

The owner's raw subs live in ``incoming/`` and **nowhere else**: no backup, no
second copy. A single stray ``unlink``/``move`` there destroys data that cannot
be regenerated by any amount of re-stacking. ``AGENTS.md`` §10 carries the prose
rule, but a prose rule is not enforcement — the next agent to build a "tidy up
your incoming folder" or "free space by removing the originals you've already
ingested" feature is exactly the failure mode this file exists to catch, in CI,
before it can ever reach the owner's NAS.

Three layers, deliberately overlapping, because each catches what the others miss:

1. :func:`_snapshot` / :func:`_assert_unchanged` — a **behavioural** check. Seed a
   realistic incoming tree, drive the real code paths that could plausibly touch
   it (scan → ingest → QC → stack, the storage clears, run prune, target merge,
   ``DELETE`` a target *with* ``remove_files=true``, sample-data load/remove,
   reprocess-all, the video pipeline), then assert every seeded file still exists
   with an unchanged size, checksum **and** mtime, and that the directory listing
   itself is unchanged. This catches real behaviour, not spelling.
2. :class:`_IncomingSentinel` — a **call-level spy**. Every destructive stdlib
   entry point (``os.remove``/``unlink``/``rmdir``/``truncate``, ``os.rename``/
   ``replace``, ``Path.unlink``/``rmdir``/``rename``/``replace``, ``shutil.move``/
   ``rmtree``/``copy*``) is wrapped for the duration of the run and **fails the
   test if it is called with a path that resolves inside the incoming folder**.
   Stronger than grepping source text: it sees the call whatever module or alias
   made it, and it fires even when the file happened not to exist yet.
3. :func:`test_ingest_still_copies_and_never_moves` — a **source** check on the
   one function where the tempting "optimisation" lives, so the classic
   `copy2` → `move` regression is caught at the line that would introduce it.

The only writes ever permitted under ``incoming/`` are the upload endpoints
*adding* new files (they skip a name that already exists — pinned below), and the
``.part`` temp sidecar each upload streams into and owns end to end. Everything
else is a violation, by construction.

If a test here fails: **do not relax it.** Find the call it caught and remove it.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import sys
import time
from pathlib import Path

import pytest

