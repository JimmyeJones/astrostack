def _seed_decoys(incoming: Path) -> None:
    """Add the shapes the fixture's two clean target folders don't cover.

    The ``data_root`` fixture already lays down ``M_42/`` and ``NGC_7000/`` with
    three Seestar subs each; these add a Seestar ``_sub`` folder, a bare on-device
    output folder, a stray non-FITS file, and a loose sub at the top level — i.e.
    the cases the scanner classifies differently, so a "clean up what I skipped"
    bug would surface here first.
    """
    sub = incoming / "M 51_sub"
    sub.mkdir(parents=True, exist_ok=True)
    for i in range(2):
        write_seestar_fits(sub / f"Light_M 51_10.0s_IRCUT_2026{i:02d}.fit",
                           width=64, height=48, n_stars=8, seed=7 + i)
    bare = incoming / "M 51"
    bare.mkdir(parents=True, exist_ok=True)
    write_seestar_fits(bare / "Stacked_60_M 51.fit", width=64, height=48,
                       n_stars=8, seed=21)
    (incoming / "M_42" / "capture-notes.txt").write_text("clear night, no moon\n")
    write_seestar_fits(incoming / "loose_frame.fit", width=64, height=48,
                       n_stars=8, seed=33)
    # Backdate everything: an mtime from "last night" makes an accidental
    # rewrite obvious rather than hiding inside the test's own second.
    old = time.time() - 86_400
    for p in incoming.rglob("*"):
        if p.is_file():
            os.utime(p, (old, old))


def _wait_job(client, job_id: str, timeout: float = 180.0) -> dict:
    deadline = time.time() + timeout
    while time.time() < deadline:
        body = client.get(f"/api/jobs/{job_id}").json()
        if body["state"] in ("done", "error", "cancelled", "interrupted"):
            return body
        time.sleep(0.05)
    raise AssertionError(f"job {job_id} did not finish in {timeout}s")


