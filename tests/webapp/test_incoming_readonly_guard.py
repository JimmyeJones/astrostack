def test_the_sentinel_actually_fires(sentinel, data_root):
    """Meta-test: prove the spy works, so a green run above means something.

    Without this, a sentinel that silently stopped wrapping anything would let
    every other test in this file pass while enforcing nothing.
    """
    victim = data_root / "incoming" / "M_42" / "frame_000.fit"
    assert victim.exists()
    victim.unlink()
    assert sentinel.violations, "the sentinel did not notice a deletion in incoming"
    assert "frame_000.fit" in sentinel.violations[0]
    with pytest.raises(AssertionError, match="incoming folder"):
        sentinel.assert_clean("meta")

    # …and it stays quiet for the app's own storage, and for an upload sidecar.
    sentinel.violations.clear()
    (data_root / "library").mkdir(parents=True, exist_ok=True)
    scratch = data_root / "library" / "scratch.bin"
    scratch.write_bytes(b"x")
    scratch.unlink()
    part = data_root / "incoming" / "M_42" / "frame_001.fit.abc.part"
    part.write_bytes(b"x")
    part.unlink()
    sentinel.assert_clean("app-owned paths")


def test_the_whole_workflow_never_deletes_or_edits_a_file_in_incoming(
        sentinel, data_root, client):
    """Drive the real destructive-looking paths end to end and check the folder.

    This is the one that would have caught a "free up space by removing ingested
    originals" feature: every endpoint below either deletes something or walks
    the incoming tree, and none of them may leave a mark on it.
    """
    incoming = data_root / "incoming"
    _seed_decoys(incoming)
    before = _snapshot(incoming)
    assert len(before) >= 10, "the decoy tree should be non-trivial"

    # Stage-1 caching ON. This is the setting that makes ingest *copy each source
    # frame*, so it is the branch where a "move it instead, we've got a copy now"
    # optimisation would live — off by default, and therefore unexercised (and
    # unguarded) unless the test asks for it explicitly.
    assert client.put("/api/settings", json={"copy_to_cache": True}).status_code == 200

    # Scan → ingest → QC (the hot path that reads every file in the folder).
    job = _wait_job(client, client.post("/api/scan").json()["job_id"])
    assert job["state"] == "done", job.get("error")
    _assert_unchanged(before, incoming, "after scan/ingest/QC")

    targets = [t["safe_name"] for t in client.get("/api/targets").json()]
    assert targets, "the scan should have produced targets to operate on"

    # Sample data — loaded and then removed with remove_files=True.
    assert client.post("/api/sample").status_code == 201
    assert client.delete("/api/sample").status_code == 200

    # A full process (QC + solve + stack) on one target, then prune its runs.
    _wait_job(client, client.post(f"/api/targets/{targets[0]}/process").json()["job_id"])
    client.post(f"/api/targets/{targets[0]}/stack-runs/prune", json={"keep": 0})

    # Every clearable cache stage.
    for stage in ("stage1", "stage2", "thumbs", "all"):
        r = client.post(f"/api/targets/{targets[0]}/cache/clear", params={"stage": stage})
        assert r.status_code == 200, r.text

    # Merge two targets into one, then delete the survivor *with its files*.
    if len(targets) > 1:
        client.post("/api/targets/merge",
                    json={"into": targets[0], "sources": [targets[1]]})
    r = client.delete(f"/api/targets/{targets[0]}", params={"remove_files": "true"})
    assert r.status_code == 200, r.text

    # Re-scan afterwards: the frames must still be there to find, which is the
    # whole point — a user can always rebuild their library from incoming.
    job = _wait_job(client, client.post("/api/scan").json()["job_id"])
    assert job["state"] == "done", job.get("error")
    assert client.get("/api/targets").json(), "re-scan found nothing to rebuild from"

    _assert_unchanged(before, incoming, "after the full destructive workflow")
    sentinel.assert_clean("the full destructive workflow")


def test_reprocess_all_leaves_the_source_frames_alone(sentinel, data_root, client):
    """Reprocess-everything walks every target and restacks it — a batch job is
    exactly where a "tidy up as you go" step would be tempting to add."""
    incoming = data_root / "incoming"
    _seed_decoys(incoming)
    _wait_job(client, client.post("/api/scan").json()["job_id"])
    before = _snapshot(incoming)

    r = client.post("/api/reprocess-all")
    assert r.status_code in (200, 202, 409), r.text
    if r.status_code < 300 and "job_id" in r.json():
        _wait_job(client, r.json()["job_id"])

    _assert_unchanged(before, incoming, "after reprocess-all")
    sentinel.assert_clean("reprocess-all")


def test_uploading_a_name_that_already_exists_never_overwrites_the_original(
        sentinel, data_root, client):
    """Upload is the one endpoint allowed to *write* under incoming — it may only
    ever add. A same-named sub is reported as skipped, byte-for-byte intact."""
    incoming = data_root / "incoming"
    _seed_decoys(incoming)
    existing = incoming / "M_42" / "frame_000.fit"
    before = _snapshot(incoming)

    original = existing.read_bytes()
    r = client.post("/api/upload", files={"files": ("frame_000.fit", b"NOT A FITS")},
                    data={"target": "M_42"})
    assert r.status_code in (200, 201), r.text
    assert [f["name"] for f in r.json()["skipped"]] == ["frame_000.fit"]
    assert r.json()["saved"] == []
    assert existing.read_bytes() == original

    _assert_unchanged(before, incoming, "after a colliding upload")
    sentinel.assert_clean("a colliding upload")

    # A genuinely new name is added — and adding is all it does.
    r = client.post("/api/upload", files={"files": ("brand_new.fit", b"hello")},
                    data={"target": "M_42"})
    assert r.status_code in (200, 201), r.text
    assert [f["name"] for f in r.json()["saved"]] == ["brand_new.fit"]
    added = {**before, "M_42/brand_new.fit": _snapshot(incoming)["M_42/brand_new.fit"]}
    _assert_unchanged(added, incoming, "after a fresh upload")
    sentinel.assert_clean("a fresh upload")

    # A zipped capture folder: unpacked in place, its own bytes never kept — the
    # ``.part`` sidecar it streams through is the one temp the app owns there.
    import io
    import zipfile

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("M 63_sub/Light_M 63_10.0s.fit", b"zipped sub")
    r = client.post("/api/upload", files={"files": ("drop.zip", buf.getvalue())},
                    data={"target": ""})
    assert r.status_code in (200, 201), r.text
    _assert_unchanged({**added, **{k: v for k, v in _snapshot(incoming).items()
                                   if k.startswith("M 63_sub/")}},
                      incoming, "after a zip upload")
    sentinel.assert_clean("a zip upload")


def test_the_video_pipeline_never_touches_the_capture_it_stacks(
        sentinel, data_root, client):
    """Moon & Sun decodes a clip *in place* out of incoming and crops the result
    in the app's own store. The source clip must come back untouched — including
    across the in-place crop and undo, which rewrite the finished still."""
    from seestack.video.ffmpeg import ffmpeg_available

    if not ffmpeg_available():
        pytest.skip("ffmpeg/ffprobe not installed (see AGENTS.md §7)")

    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from videosynth import lunar_video

    cap = data_root / "incoming" / "Lunar_video"
    cap.mkdir(parents=True, exist_ok=True)
    lunar_video(cap / "clip.mp4", n_frames=10, sharp_indices=(1, 4, 7), w=64, h=48)
    _seed_decoys(data_root / "incoming")
    before = _snapshot(data_root / "incoming")

    job = _wait_job(client, client.post("/api/videos/Lunar_video/stack",
                                        json={"keep_percent": 30}).json()["job_id"])
    assert job["state"] == "done", job.get("error")
    client.post("/api/videos/Lunar_video/crop")
    client.post("/api/videos/Lunar_video/uncrop")

    _assert_unchanged(before, data_root / "incoming", "after the video pipeline")
    sentinel.assert_clean("the video pipeline")


def test_ingest_still_copies_and_never_moves():
    """The source-level backstop for the one "optimisation" that would be fatal.

    Ingest reads from the owner's only copy and writes into the app's cache. Turn
    that ``shutil.copy2`` into a ``move``/``rename``/hardlink-plus-unlink and the
    subs stop existing the moment they are ingested — with the app looking, to
    every test that only checks the library, entirely healthy.
    """
    src = (Path(__file__).resolve().parents[2] / "seestack" / "io" / "ingest.py").read_text()
    assert "shutil.copy2(" in src, (
        "ingest no longer copies — it MUST copy out of the incoming folder "
        "(AGENTS.md §10); the owner's raw subs have no second copy.")
    for banned in ("shutil.move(", "os.rename(", "os.replace(", ".rename(",
                   ".replace(", "os.link(", "os.unlink(", ".unlink(",
                   "os.remove("):
        assert banned not in src, (
            f"ingest.py contains {banned!r} — ingest may only *read* the source "
            "frame and *copy* it (AGENTS.md §10).")


def test_the_scanner_only_reads_the_incoming_tree():
    """Same backstop for the module that walks the folder deciding what to do."""
