from rl import *
t0 = time.strftime('%H:%M:%S')
print("--- stacked image"); im = urllib.request.urlopen(B + "/api/image?kind=full", timeout=30).read(); print("     full image bytes", len(im), im[:2] == b"\xff\xd8", "| image", st()["image"])
print("--- stop stack"); act("stop_stack")
s = wait(lambda s: s["view"]["stage"] != "Stack" and s["stack"]["state"] != "working", 40, "stack stopped"); brief(s)
print("--- live preview video")
try: urllib.request.urlopen(B + "/api/video_frame", timeout=8).read()
except Exception as e: print("     first frame req:", e)
s = wait(lambda s: s["video"]["live"], 40, "preview live"); print("     video", s["video"])
try:
    fr = urllib.request.urlopen(B + "/api/video_frame", timeout=8).read(); print("     frame bytes", len(fr), fr[:2] == b"\xff\xd8")
    open("preview.jpg", "wb").write(fr)
except Exception as e: print("     frame:", e)
print("--- plate solve"); act("solve")
s = wait(lambda s: s["solve"] and not s["solve"].get("error") , 60, "solve result"); print("     solve", json.dumps(s["solve"])[:300])
print("--- autofocus"); act("autofocus_start"); time.sleep(6); act("autofocus_stop"); time.sleep(4)
act("autofocus_start"); wait(lambda s: any("AutoFocus complete" in str(l["text"]) for l in s["log"][-12:]), 120, "autofocus complete"); print("     focus", st()["focus"])
print("--- preview exposure"); act("set_preview_exposure", {"value": 1000}); wait(lambda s: s["settings"]["exp_ms"]["continuous"] == 1000, 25, "continuous=1000")
act("set_preview_exposure", {"value": 500}); wait(lambda s: s["settings"]["exp_ms"]["continuous"] == 500, 25, "continuous=500")
print("--- start stack (resume)"); act("start_stack", {"restart": False})
s = wait(lambda s: s["view"]["stage"] == "Stack" and s["stack"]["state"] == "working", 60, "stacking again"); brief(s)
log(45, t0)
print(json.dumps(rpc("get_view_state"))[:700])
