# --------------------------------------------------------------------------- #
# Layer 1 — the behavioural snapshot
# --------------------------------------------------------------------------- #

def _snapshot(root: Path) -> dict[str, tuple[int, str, int]]:
    """Every file under ``root`` → (size, sha256, mtime_ns).

    mtime is included deliberately: a rewrite that happened to reproduce the same
    bytes is still the app writing into a folder it must only read.
    """
    out: dict[str, tuple[int, str, int]] = {}
    for p in sorted(root.rglob("*")):
        if not p.is_file():
            continue
        st = p.stat()
        out[str(p.relative_to(root))] = (
            st.st_size, hashlib.sha256(p.read_bytes()).hexdigest(), st.st_mtime_ns)
    return out


def _assert_unchanged(before: dict, root: Path, what: str) -> None:
    after = _snapshot(root)
    lost = sorted(set(before) - set(after))
    assert not lost, (
        f"{what}: {len(lost)} file(s) VANISHED from the incoming folder — {lost[:5]}. "
        "The owner's raw subs exist there and nowhere else (AGENTS.md §10); this is "
        "unrecoverable data loss, not a test to relax.")
    changed = sorted(k for k in before if after[k] != before[k])
    assert not changed, (
        f"{what}: {len(changed)} file(s) were MODIFIED in place in the incoming "
        f"folder — {changed[:5]}. The app may only read there (AGENTS.md §10).")
    assert set(after) == set(before), (
        f"{what}: the incoming listing changed — unexpected new entries "
        f"{sorted(set(after) - set(before))[:5]}.")


# --------------------------------------------------------------------------- #
# Layer 2 — the call-level spy
# --------------------------------------------------------------------------- #

# An upload streams into a unique ``<name>.<rand>.part`` sidecar next to its
# destination and atomically renames it into place; a failed upload removes its
# own sidecar. That temp is created, owned and cleaned up by the same request, so
# it is the one path under incoming the app is allowed to delete or rename. It is
# never a user file: the scanner's FITS glob skips ``.part`` entirely.
def _is_own_upload_temp(p: Path) -> bool:
    return p.suffix == ".part"


class _IncomingSentinel:
    """Wraps the destructive stdlib calls and records any that reach ``incoming``."""

    def __init__(self, incoming: Path) -> None:
        self.root = incoming.resolve()
        self.violations: list[str] = []

    def _inside(self, path) -> Path | None:  # noqa: ANN001
        """The resolved path if it lands under incoming, else ``None``.

        Symlinks and ``..`` are resolved first — a NAS mount symlinked into the
        data root must not be a way around the rule.
        """
        try:
            p = Path(os.fspath(path)).resolve()
        except (OSError, TypeError, ValueError):
            return None
        return p if p == self.root or self.root in p.parents else None

    def _flag(self, call: str, path) -> None:  # noqa: ANN001
        p = self._inside(path)
        if p is not None and not _is_own_upload_temp(p):
            self.violations.append(f"{call}({p})")

    def _flag_overwrite(self, call: str, dst) -> None:  # noqa: ANN001
        """A *destination* inside incoming is only legal if nothing is there.

        ``os.replace``/``shutil.copy*`` silently clobber an existing file, so
        "the app only ever adds" has to mean the target did not exist.
        """
        p = self._inside(dst)
        if p is not None and p.exists() and not _is_own_upload_temp(p):
            self.violations.append(f"{call}(→ {p}) would overwrite an existing file")

    def arm(self, monkeypatch: pytest.MonkeyPatch) -> None:
        # (module/class, attribute) pairs. Patching the *attribute* catches the
        # ``os.remove(...)`` / ``p.unlink()`` call styles the codebase uses.
        for owner, name in ((os, "remove"), (os, "unlink"), (os, "rmdir"),
                            (os, "truncate"), (shutil, "rmtree"),
                            (Path, "unlink"), (Path, "rmdir")):
            self._wrap_target(monkeypatch, owner, name)
        for owner, name in ((os, "rename"), (os, "replace"), (shutil, "move"),
                            (Path, "rename"), (Path, "replace")):
            self._wrap_move(monkeypatch, owner, name)
        for name in ("copy", "copy2", "copyfile"):
            self._wrap_copy(monkeypatch, shutil, name)

    def _label(self, owner, name: str) -> str:  # noqa: ANN001
        return f"{getattr(owner, '__name__', owner.__class__.__name__)}.{name}"

    def _wrap_target(self, monkeypatch, owner, name) -> None:  # noqa: ANN001
        orig, label = getattr(owner, name), self._label(owner, name)

        def guard(path, *a, **kw):  # noqa: ANN001 — `path` is self for Path methods
            self._flag(label, path)
            return orig(path, *a, **kw)

        monkeypatch.setattr(owner, name, guard)

    def _wrap_move(self, monkeypatch, owner, name) -> None:  # noqa: ANN001
        orig, label = getattr(owner, name), self._label(owner, name)

        def guard(src, dst, *a, **kw):  # noqa: ANN001
            self._flag(label, src)          # moving a file *out* of incoming
            self._flag_overwrite(label, dst)  # or clobbering one still in it
            return orig(src, dst, *a, **kw)

        monkeypatch.setattr(owner, name, guard)

    def _wrap_copy(self, monkeypatch, owner, name) -> None:  # noqa: ANN001
        orig, label = getattr(owner, name), self._label(owner, name)

        def guard(src, dst, *a, **kw):  # noqa: ANN001
            self._flag_overwrite(label, dst)
            return orig(src, dst, *a, **kw)

        monkeypatch.setattr(owner, name, guard)

    def assert_clean(self, what: str) -> None:
        assert not self.violations, (
            f"{what}: {len(self.violations)} destructive call(s) reached the "
            f"incoming folder — {self.violations[:5]}. The owner's only copy of "
            "their raw subs lives there (AGENTS.md §10): the app may read and "
            "create-new, never delete, move, rename, truncate or overwrite.")


@pytest.fixture
def sentinel(data_root: Path, monkeypatch: pytest.MonkeyPatch) -> _IncomingSentinel:
    """Arm the spy before anything else in the test touches the app."""
    s = _IncomingSentinel(data_root / "incoming")
    s.arm(monkeypatch)
    return s


